"""Split Category.creator_price into three difficulty-keyed levels.

Written by hand rather than autogenerated because the three new columns
have to be **backfilled from the old one before** they are made
non-nullable. Autogeneration would either demand a single default for
every existing category or leave the columns nullable, and both would
change what creators are paid.

The backfill copies the current price into all three levels, so every
existing category pays exactly what it paid before this migration ran.
Differentiating the tiers is then a deliberate admin edit, not a side
effect of a deploy.
"""

from decimal import Decimal

from django.core.validators import MinValueValidator
from django.db import migrations, models


def copy_price_into_levels(apps, schema_editor):
    Category = apps.get_model("catalog", "Category")
    Category.objects.update(
        creator_price_beginner=models.F("creator_price"),
        creator_price_intermediate=models.F("creator_price"),
        creator_price_advanced=models.F("creator_price"),
    )


def collapse_levels_into_price(apps, schema_editor):
    """Reverse: the beginner rate becomes the single price again.

    Lossy by nature - three numbers cannot round-trip into one - so the
    entry rate is chosen deliberately as the conservative floor.
    """

    Category = apps.get_model("catalog", "Category")
    Category.objects.update(creator_price=models.F("creator_price_beginner"))


